import { useEffect, useState } from 'react';
import { HERO_IMAGES } from '../data/site';

/**
 * Нүүр хуудасны дэвсгэр зургууд — автоматаар солигдоно.
 *
 * Зураг угаалгах гэж буй хүнд «энэ газар ямар чанартай ажилладаг вэ» гэдгийг
 * градиент биш, бодит ажлын зураг л хэлж чадна.
 *
 * Гүйцэтгэлийн шийдлүүд:
 *   • ЗӨВХӨН эхний зураг `fetchPriority="high"`-тэй.
 *   • ⚠️ Бусад зургийг эхний зураг ГАРЧ ИРТЭЛ огт үүсгэхгүй. `loading="lazy"`
 *     нь энд ТУСЛАХГҮЙ: дөрвүүлээ дэлгэцийн харагдах хэсэгт (`absolute
 *     inset-0`) байрладаг тул хөтөч бүгдийг нь ШУУД татна. Үр дүнд нь нүүр
 *     хуудас нээхэд дөрвөн зураг зэрэг татагдаж, эхнийх нь удаашрана.
 *   • Солих нь `opacity` шилжилт: layout дахин тооцоологддоггүй тул хямд.
 *   • Таб нуугдсан үед зогсоно — арын табанд таймер эргүүлэх нь батарей иддэг.
 *
 * Хүртээмж:
 *   • `prefers-reduced-motion` тохируулсан хүнд автомат солилт ажиллахгүй —
 *     хөдөлгөөнөөс толгой эргэдэг хүмүүс байдаг.
 *   • Зургууд бүгд `aria-hidden` — чимэглэл учир дэлгэц уншигчид хэрэггүй.
 */

/**
 * Хэдэн секунд тутам солих вэ.
 *
 * 2 секунд нь хэт хурдан байв — зураг тогтож амжаагүй байхад дараагийнх нь
 * ирж, дэвсгэр анивчсан мэдрэмж төрүүлдэг. 5 секунд нь зураг бүрийг үнэхээр
 * ХАРАХ зав өгнө.
 *
 * ⚠️ Шилжилтийн хугацаа (700ms) нь мөчлөгийн 14% — зураг тогтох зай элбэг.
 */
const INTERVAL_MS = 5000;

/**
 * Зураг хажуу тийш ГУЛСАХ хугацаа.
 *
 * ── Яагаад уусалт биш гулсалт вэ ─────────────────────────────────
 *
 * Уусалт нь мөн чанараараа хоёр зургийг ЗЭРЭГ хагас тунгалагаар
 * үзүүлдэг. Хийсвэр дэвсгэр дээр энэ нь сайхан. Гэтэл манай зураг бүр
 * дээр том, танигдахуйц МАШИН байгаа бөгөөд тэд өөр өөр байрлалд
 * зогсдог: уусалтын дунд цэгт хоёр машин давхарлаж, Epson-ы доогуур
 * Konica-гийн тавиур уншигдана. Нүд үүнийг алдаа гэж уншдаг.
 *
 * Гулсалт дээр цэг бүр дээр ЯГ НЭГ зураг харагдана — давхарлах
 * боломжгүй тул энэ асуудал бүрмөсөн алга болно.
 *
 * 650ms нь зориуд богино: гулсалт удаан бол карусель хүндэрч,
 * хүн дуусахыг нь хүлээдэг.
 */
const SLIDE_MS = 650;

/**
 * Зураг бүрийн КАМЕРЫН ХӨДӨЛГӨӨН.
 *
 * ── Яагаад хүснэгт вэ ─────────────────────────────────────────────
 *
 * Урьд нь ердөө хоёр хөдөлгөөн ээлжилдэг байв: тэгш дугаар ойртоно,
 * сондгой нь холдоно. Дөрвөн зурагтай слайд дээр хүн хоёр дахь
 * эргэлтэд давталтыг нь анзаардаг — «ойртоно, холдоно, ойртоно,
 * холдоно» нь камерын хөдөлгөөн биш, хэмнэл болж сонсогддог.
 *
 * Бодит оператор зураг бүрийг өөрөөр авна: заримыг нь ойртуулж,
 * заримыг нь холдуулж, заримыг нь хажуу тийш шилжүүлж. Тиймээс
 * хөдөлгөөн бүр ӨӨР.
 *
 * ⚠️ `scale(1)` дээр ИЛҮҮДЭЛ ЗАЙ БАЙХГҮЙ тул тэнд `translate` хийвэл
 * зургийн ирмэг гарч, хоосон зурвас харагдана. Иймд `scale(1)`-тэй
 * байрлал үргэлж `translate(0, 0)`. Бусад дээр шилжилт нь
 * (scale − 1) / 2-оос хэтрэхгүй: 1.06 дээр дээд тал нь 3%.
 */
const CAMERA = [
  /* Аажим ойртолт — зүүн дээш. */
  { from: 'scale(1) translate(0, 0)', to: 'scale(1.07) translate(-1.2%, -0.8%)' },
  /* Холдолт — баруун доороос төв рүү. */
  { from: 'scale(1.07) translate(1.2%, 0.7%)', to: 'scale(1) translate(0, 0)' },
  /* Цэвэр хажуу шилжилт — ойртолтгүй тул «тавиур дээрх камер» мэдрэмж. */
  { from: 'scale(1.05) translate(1.4%, -0.4%)', to: 'scale(1.05) translate(-1.4%, 0.4%)' },
  /* Холдолт — зүүн дээрээс. */
  { from: 'scale(1.06) translate(-1%, -0.8%)', to: 'scale(1) translate(0, 0)' },
];

const prefersReducedMotion = (): boolean =>
  typeof matchMedia === 'function' &&
  matchMedia('(prefers-reduced-motion: reduce)').matches;

export default function HeroSlideshow() {
  /**
   * Одоогийн ба гарч буй зураг — НЭГ төлөвт.
   *
   * ⚠️ Хоёр тусдаа `useState` байж БОЛОХГҮЙ. Солилт нь хоёуланг нь ЗЭРЭГ
   * өөрчилдөг тул `setIndex`-ийн шинэчлэгч дотроос `setPrev` дуудах
   * уруу татдаг — гэтэл шинэчлэгч нь ЦЭВЭР функц байх ёстой. React
   * түүнийг зурагдах үед, бүр хоёр ч удаа дуудаж болдог тул тэнд
   * хажуугийн үйлдэл хийвэл «өөр бүрэлдэхүүнийг зурж байх үед шинэчлэв»
   * гэх алдаа гарна.
   *
   * Нэг объект болгосноор шинэчлэгч нь цэвэр хэвээр үлдэнэ.
   */
  const [slide, setSlide] = useState<{ index: number; prev: number | null }>({
    index: 0,
    prev: null,
  });
  /**
   * `prev` — ГАРЧ БУЙ зураг, уусалт дуустал ХАРАГДСАН хэвээр.
   *
   * ⚠️ Урьд нь бүх идэвхгүй зураг `opacity: 0` байв. Уусалтын ДУНД цэгт
   * хоёул 50% тунгалаг болж, доорх `bg-ink` шууд цухуйдаг: нийт
   * бүрхэлт 0.5 + 0.5×0.5 = 75% л болно. Үр дүнд нь солилт бүр дээр
   * дэвсгэр бараан руу «цохиж» аваад буцдаг байлаа — энэ нь кино
   * уусалт биш, анивчилт.
   *
   * Одоо гарч буй зураг БҮРЭН тунгалаг бус хэвээр доор нь үлдэж,
   * шинэ зураг түүний ДЭЭГҮҮР бүдгээс тод руу ирнэ. Бүрхэлт ямагт
   * 100% тул дэвсгэр хэзээ ч харагдахгүй.
   */
  const { index, prev } = slide;

  /**
   * Уусалт дуусмагц гарсан зургийг ЧӨЛӨӨЛНӨ.
   *
   * ⚠️ Үүнгүй бол хоёрхон зурагтай слайд ЗОГСОНО: зураг эргэж ирэхдээ
   * хөдөлгөөнөө ЭХНЭЭСЭЭ эхлэх ёстой ч «гарч буй» төлөвт байх хугацаандаа
   * эцсийн байрлалдаа зогссон хэвээр үлдэж, дахин хөдлөхгүй болно.
   *
   * Чөлөөлөлт нь хоёр давхар тунгалаг бус зургийн ДОР болдог тул
   * байрлалын үсрэлт харагдахгүй.
   */
  useEffect(() => {
    if (prev === null) return;
    const id = setTimeout(
      () => setSlide((current) => ({ ...current, prev: null })),
      SLIDE_MS,
    );
    return () => clearTimeout(id);
  }, [prev]);

  const goTo = (next: number) =>
    setSlide((current) =>
      next === current.index ? current : { index: next, prev: current.index },
    );

  /**
   * Эхний зураг гарсны дараа л үлдсэнийг DOM-д нэмнэ.
   *
   * Ингэснээр анхны зурагдалт нь ЗӨВХӨН нэг зургийн татахыг хүлээнэ.
   * Үлдсэн нь араас чимээгүй ирнэ — эхний солилт 5 секундын дараа тул
   * амжина.
   */
  const [ready, setReady] = useState(false);

  /**
   * Эхний зургийн ойртолтыг асаах түлхүүр.
   *
   * ⚠️ Үүнгүй бол ЭХНИЙ зураг хөдөлдөггүй. CSS-ийн шилжилт нь утга
   * ӨӨРЧЛӨГДӨХӨД л ажилладаг: эхний зурагдалтад `index === 0` тул React
   * түүнийг шууд эцсийн хэмжээтэй нь буулгаж, шилжих зай үлдэхгүй.
   *
   * Нэг кадр хүлээгээд асаахад утга өөрчлөгдөж, ойртолт эхэлнэ. Хуудас
   * нээх агшин бол хамгийн их харагддаг тул энэ нь чухал.
   */
  const [started, setStarted] = useState(false);
  useEffect(() => {
    const id = requestAnimationFrame(() => setStarted(true));
    return () => cancelAnimationFrame(id);
  }, []);

  /**
   * Таб харагдаж байна уу.
   *
   * ⚠️ Урьд нь таймер нь `setInterval` байж, таб нуугдсан үед зүгээр л
   * АЛГАСДАГ байв. Үр дүнд нь хэмнэл алдагддаг: хүн буцаж ирэхэд
   * дараагийн солилт 0–5 секундын хооронд дурын мөчид ирнэ.
   *
   * Зүгээр үзэхэд мэдэгддэггүй байсан ч цэгэн товч дээрх явцын зураас
   * үүнийг ИЛ болгоно — зураас дүүрчихээд зураг солигдохгүй зогсоно.
   * Тиймээс одоо үнэхээр ЗОГСООНО.
   */
  const [visible, setVisible] = useState(
    () => typeof document === 'undefined' || !document.hidden,
  );
  useEffect(() => {
    const sync = () => setVisible(!document.hidden);
    document.addEventListener('visibilitychange', sync);
    return () => document.removeEventListener('visibilitychange', sync);
  }, []);

  const autoplay = HERO_IMAGES.length > 1 && visible && !prefersReducedMotion();

  /**
   * Нэг зураг хэр удаан зогсох вэ.
   *
   * ⚠️ `setInterval` биш `setTimeout`, бөгөөд `index`-ээс хамаарна: зураг
   * солигдох бүрт тоолол ШИНЭЭР эхэлнэ. Ингэснээр цэгэн товчийг гараар
   * дармагц тухайн зураг бүтэн хугацаагаа авна — урьд нь тасралтгүй
   * явдаг `setInterval`-ийн үлдсэн хэсгийг л авдаг байв.
   *
   * Мөн явцын зураас яг энэ тоололтой хамт эхэлнэ.
   */
  useEffect(() => {
    if (!autoplay) return;

    const id = setTimeout(() => {
      setSlide((current) => ({
        index: (current.index + 1) % HERO_IMAGES.length,
        prev: current.index,
      }));
    }, INTERVAL_MS);

    return () => clearTimeout(id);
  }, [autoplay, index]);

  /*
   * Зураг байхгүй бол градиент руу буцна.
   *
   * `public/hero/` хоосон байхад хуудас эвдрэх ёсгүй — шинэ deploy дээр зураг
   * оруулж амжаагүй байх нь бодитой.
   */
  if (HERO_IMAGES.length === 0) {
    return (
      <div
        aria-hidden
        className="absolute inset-0 bg-gradient-to-br from-brand-400 via-brand-500 to-brand-700"
      />
    );
  }

  return (
    /*
      * ⚠️ `isolate` ЗААВАЛ — доорх цэнхэр хальс `mix-blend-color`
      * хэрэглэдэг. Үүнгүй бол холилт нь энэ хэсгээс ГАДАГШ, доор нь
      * байрлах юмтай холбогдож болно.
      *
      * `bg-ink` нь зураг ачаалагдтал харагдах өнгө. Урьд нь `bg-brand-500`
      * байсан ч одоо дэвсгэрийг будахаа больсон тул цэнхэр анивчилт нь
      * эцсийн харагдацтай таарахгүй байв.
      */
    <div aria-hidden className="absolute inset-0 isolate overflow-hidden bg-ink">
      {HERO_IMAGES.map((image, i) =>
        i > 0 && !ready ? null : (
          <div
            key={image.src}
            /*
             * ── ГУЛСАХ БҮРХҮҮЛ ────────────────────────────────────────
             *
             * ⚠️ Яагаад зураг дээр нь шууд биш, тусдаа бүрхүүл дээр вэ:
             * гулсалт ба камерын хөдөлгөөн ХОЁУЛАА `transform` ашигладаг.
             * Нэг мөрөнд нийлүүлбэл хоёулаа НЭГ үргэлжлэлтэй болно —
             * гэтэл гулсалт 0.65 секунд, камер 7 секунд байх ёстой.
             * Тусад нь давхарлавал тус бүр өөрийн хугацаатай явна.
             */
            className="absolute inset-0 will-change-transform"
            style={(() => {
              const live = i === index || i === prev;

              return {
                /*
                 * ⚠️ ТҮЛХЭЛТ: гарч буй нь зүүн тийш, орж ирж буй нь
                 * баруунаас. Хоёулаа ижил хугацаа, ижил хурдатгалтай тул
                 * яг хажуу хажуугаа барьж явна — завсар үүсэхгүй.
                 *
                 * Идэвхгүй зургууд баруун талд (100%) ЗОГСООД хүлээнэ.
                 */
                transform: `translateX(${i === index ? 0 : i === prev ? -100 : 100}%)`,
                /*
                 * ⚠️ Зөвхөн ХӨДӨЛЖ байгаа хоёрт шилжилт өгнө. Хүлээж буй
                 * зургууд 0ms-тэй — байрандаа чимээгүй буцаж очих ёстой,
                 * эс бөгөөс дэлгэц хөндлөн гулсаж өнгөрнө.
                 */
                transitionProperty: 'transform',
                transitionDuration: live ? `${SLIDE_MS}ms` : '0ms',
                transitionTimingFunction: 'cubic-bezier(0.65, 0, 0.35, 1)',
                zIndex: i === index ? 2 : i === prev ? 1 : 0,
              };
            })()}
          >
            <img
              src={image.src}
              alt=""
              onLoad={i === 0 ? () => setReady(true) : undefined}
              /*
               * ⚠️ Алдаа гарсан ч үлдсэнийг нээнэ. Эс тэгвээс эхний зураг
               * ирэхгүй бол дэвсгэр мөнхөд ганц өнгө хэвээр үлдэнэ.
               */
              onError={i === 0 ? () => setReady(true) : undefined}
              fetchPriority={i === 0 ? 'high' : 'low'}
              decoding="async"
            /*
               * ⚠️ Хүрээ нарийн байх бүх өргөнд байрлалыг БАРУУН тийш шилжүүлнэ.
               *
               * Эх зураг 1376×768 (харьцаа 1.79) бөгөөд хэвлэгч нь голоос
               * баруун тийш байрладаг. `object-cover` нь хүрээний харьцаа 1.79-өөс
               * бага үед ӨРГӨНӨӨС, голоос нь тэгш тасалдаг — субьект нь голд
               * биш тул баруун тал нь эхэлж алга болно.
               *
               * ⚠️ Урьд нь `sm:` (640px) дээр голд нь буцаадаг байсан бөгөөд
               * тайлбар нь «sm-ээс дээш бүх зураг багтана» гэсэн. Тэр нь БУРУУ
               * байв — хүрээний өндөр нь текстээс хамаардаг тул бодит хэмжилт:
               *
               *   375px  → харьцаа 0.68 → өргөний  38% харагдана
               *   768px  → харьцаа 1.19 → өргөний  67%   (iPad — хэвлэгч тасарна)
               *   1024px → харьцаа 1.53 → өргөний  85%
               *   1280px → харьцаа 1.91 → өргөний 100%   ← энд л жинхэнэ багтана
               *
               * Тиймээс голд нь буцаах цэг `xl:` (1280px). Дунд өргөнд шилжилтийг
               * сулруулна: тасрах хэмжээ багасах тусам 50% руу ойртуулахгүй бол
               * зургийн баруун ирмэг хоосон зурвас болж гарч ирнэ.
               */
              /*
               * ⚠️ Хөнгөн тодруулга — өнгийг ГУЙВУУЛАХГҮЙ.
               *
               * Эх зургууд нь үйлдвэрлэгчийн каталогийн кадр: оффисын
               * сарниулсан гэрэлд авсан тул өөрсдөө бага зэрэг бүдэг,
               * контраст багатай.
               *
               * `brightness`/`saturate` нь өнгөний ӨНЦГИЙГ (hue) хөнддөггүй —
               * зөвхөн тодрол нэмнэ. Утгууд нь болгоомжтой: 1.2-оос дээш
               * бол цагаан хана шатаж, машины цагаан бүрхүүлтэй нийлнэ.
               */
              className="absolute inset-0 size-full object-cover object-[72%_center] brightness-110 saturate-[1.18] contrast-[1.05] will-change-transform sm:object-[66%_center] lg:object-[60%_center] xl:object-center"
              /*
               * ── Камерын хөдөлгөөн ─────────────────────────────────
               *
               * Идэвхтэй зураг 7 секундын турш `CAMERA`-гийн замаар ААЖИМ
               * хөдөлнө. Солигдох мөчлөг 5 секунд тул хөдөлгөөн нь
               * дуусахаас ӨМНӨ дараагийнх нь эхэлдэг — зогсолт мэдрэгдэхгүй.
               *
               * ⚠️ Гарч буй зураг ХӨДӨЛСӨӨР гулсана. Байрлалаа зөвхөн
               * дэлгэцнээс БҮРЭН гарсныхаа дараа (`prev` чөлөөлөгдөхөд)
               * чимээгүй эхэндээ буцааж тавина.
               *
               * `prefers-reduced-motion` үед `index.css`-ийн нэгдсэн дүрэм
               * бүх үргэлжлэлийг 0.01ms болгодог тул зураг шууд эцсийн
               * байрлалдаа суух бөгөөд энэ нь зүгээр л бага зэрэг ойрсон
               * хөдөлгөөнгүй зураг — эвдрэхгүй.
               */
              style={(() => {
                const camera = CAMERA[i % CAMERA.length];
                const live = i === index || i === prev;

                return {
                  /*
                   * `started`-гүй бол ЭХНИЙ зураг хөдөлдөггүй: CSS-ийн
                   * шилжилт нь утга ӨӨРЧЛӨГДӨХӨД л ажилладаг тул React
                   * түүнийг анхны зурагдалтад шууд эцсийн байрлалд буулгана.
                   */
                  transform: live && started ? camera.to : camera.from,
                  transitionProperty: 'transform',
                  /* Бодит камер хөдөлгөөнийхөө дундуур хурдаа өөрчилдөггүй. */
                  transitionTimingFunction: 'linear',
                  transitionDuration: live ? '7000ms' : '0ms',
                };
              })()}
            />
          </div>
        ),
      )}

      {/*
       * ── 1. ЦЭНХЭР ХАЛЬС — брэндийн уур амьсгал ─────────────────────
       *
       * `mix-blend-color` нь ӨНГИЙГ (hue + saturation) энэ давхаргаас,
       * ГЭРЭЛТҮҮЛГИЙГ доорх зурагнаас авна. `bg-brand-500` нь логоны
       * хавтантай ижил токен тул өнгө нь тодорхойлолтоороо таарна.
       *
       * ⚠️ Хальс нь ЖИГД БИШ, радиал градиент — тайлбарыг `index.css`-ийн
       * `hero-tint`-ээс үз. Товчоор: МАШИН дээр нүхтэй тул тэр нь жинхэнэ
       * өнгөөрөө харагдаж, эргэн тойрон нь цэнхэрт уусна.
       *
       * Жигд хальс нь хоёр шаардлагын аль нэгийг үргэлж золиосолдог:
       * 50% дээр зураг будагдаж, 25% дээр цэнхэр алга болно.
       *
       * Доорх халхавч нь СААРМАГ (`ink`) — цэнхэр байвал хальс дээр
       * хальс давхарлаж, будагдах асуудал буцаж ирнэ.
       */}
      {/*
       * ⚠️ `z-10` ЗААВАЛ. Зургууд уусалтын дарааллаа барихын тулд
       * `z-index` 0/1/2 авдаг — байрлалтай, z-тэй элемент нь z-гүй
       * (`auto`) элементийн ДЭЭГҮҮР гарна, DOM-д хэдийд ч бичигдсэн
       * байлаа гэсэн. Энэ давхаргууд z-гүй байвал зургийн ДОР үлдэж,
       * цэнхэр хальс ч, текстийн халхавч ч, цэгэн товч ч алга болно.
       */}
      <div className="hero-tint absolute inset-0 z-10" />

      {/*
       * ── 2. ЦЭНХЭР БУДАГ — зөвхөн дэвсгэр дээр ──────────────────────
       *
       * Дээрх хальс нь `mix-blend-color` тул ГЭРЭЛТҮҮЛГИЙГ зурагнаас
       * авдаг: цэнхэр нь зургийн гэрэл сүүдрийг дагаж хэлбэлзэж, оффисын
       * цайвар хана дээр саарал болдог. Брэндийн цэнхэр бол ХАВТГАЙ өнгө.
       *
       * Энэ давхарга бол энгийн будаг (blend-гүй): машинаас хол зай нь
       * шууд брэндийн өнгө болж, ойрхон нь зураг хэвээр үлдэнэ.
       *
       * ⚠️ Нүх нь `hero-tint`-тэй ижил (`--hero-subject`) тул машин
       * бүрэн тод хэвээр — будаг нь ЗӨВХӨН эргэн тойронд нэмэгдэнэ.
       */}
      <div className="hero-wash absolute inset-0 z-10" />

      {/*
       * ── 3. Текстийн контраст — өнгө ЗАСАХГҮЙ ───────────────────────
       *
       * ⚠️ Урьд нь энд `bg-brand-500 mix-blend-color` тонгоруулга байсан:
       * зургийн өнгийг бүхэлд нь брэндийн цэнхэр рүү татдаг байв. Үр дүнд
       * нь хэвлэгчийн бодит өнгө (саарал метал, модон ширээ, дэлгэцийн
       * гэрэл) бүгд нэг цэнхэр болж, зураг нь ГЭРЭЛ ЗУРАГ биш, будсан
       * чимэглэл мэт харагддаг байлаа.
       *
       * Одоо зураг ЖИНХЭНЭ ӨНГӨӨРӨӨ гарна — `ppm32.mn` дээрх ажлын
       * зургуудтай ижил. Брэндийн өнгө нь товч, гарчиг, толгой дээр
       * хангалттай байгаа тул дэвсгэрийг будах шаардлагагүй.
       *
       * Үлдсэн хоёр давхарга нь ЗӨВХӨН уншигдац: цагаан гарчиг, товч
       * зургийн цайвар хэсэг дээр суувал алга болно. Тиймээс саармаг
       * бараан (`--color-ink`) — цэнхэр БИШ, эс бөгөөс өнгө дахин
       * хальсална.
       *
       * ⚠️ Эдгээр нь урьд нь ХАМГИЙН ГОЛ халхавч байв (85/70/45). Тэр
       * үед дэвсгэрийн өнгийг тогтоох өөр юм байгаагүй тул гарчгийн
       * уншигдац бүхэлдээ эндээс хамаардаг байлаа.
       *
       * Гэвч `ink` бол СААРМАГ бараан: хэдий чинээ их байна төдий чинээ
       * цэнхэр нь хар хөх рүү татагдана. Хэмжилтээр манай зүүн тал
       * #2b3c72 байсан бол брэндийн өнгө #4472e0 — бараг хоёр дахин
       * бараан. Өөрөөр хэлбэл халхавч нь брэндийн өнгийг ИДЭЖ байв.
       *
       * Одоо дэвсгэрийг `hero-wash` тогтоодог тул эдгээр нь зөвхөн
       * ҮЛДЭГДЭЛ үүрэгтэй: ширээн дээр бараг тэг, утсан дээр л бага
       * зэрэг (тэнд бичиг зургийн БҮХ өргөнөөр тардаг).
       * Босоо: доод ирмэг бага зэрэг — слайдын цэгүүд тэнд сууна.
       */}
      {/*
       * ⚠️ Утас ба ширээний компьютерт ӨӨР халхавч.
       *
       * Ширээн дээр бичиг нь зүүн талд багтдаг тул халхавч зүүнээс баруун
       * тийш бүдгэрч, хэвлэгч баруун талд ЦЭВЭР харагдана.
       *
       * Утсан дээр бичиг БҮТЭН өргөнөөр тардаг: тэр градиентийг хэвээр
       * үлдээвэл гарчгийн баруун үзүүр («…үйлчилгээ») зургийн гэгээн
       * хэсэг дээр сууж, амбер текст уншигдахаа болино. Тиймээс нарийн
       * дэлгэцэд халхавчийг жигд гүн болгоно.
       */}
      <div className="absolute inset-0 z-10 bg-gradient-to-r from-ink/30 via-ink/18 to-ink/8 sm:from-ink/4 sm:via-transparent sm:to-transparent" />
      <div className="absolute inset-0 z-10 bg-gradient-to-t from-ink/14 via-transparent to-transparent" />

      {HERO_IMAGES.length > 1 && (
        <div className="absolute bottom-4 left-1/2 z-20 flex -translate-x-1/2 gap-2 sm:bottom-6">
          {HERO_IMAGES.map((image, i) => (
            <button
              key={image.src}
              type="button"
              onClick={() => goTo(i)}
              aria-label={`${i + 1} дэх зураг`}
              aria-current={i === index}
              className={`h-1.5 overflow-hidden rounded-full transition-all ${
                i === index ? 'w-6 bg-white/35' : 'w-1.5 bg-white/50 hover:bg-white/80'
              }`}
            >
              {/*
               * Идэвхтэй цэг нь дараагийн зураг хүртэлх ЯВЦЫГ дүүргэнэ.
               *
               * ⚠️ `key` нь `index` — зураг солигдох бүрт React үүнийг
               * ШИНЭЭР үүсгэнэ. Үүнгүй бол CSS-ийн хөдөлгөөн нэг л удаа
               * ажиллаад зогсоно: нэг элемент дээр ижил `animation`
               * дахин эхэлдэггүй.
               *
               * Автомат солилт зогссон үед (таб нуугдсан, эсвэл хөдөлгөөн
               * хумисан тохиргоотой) зураас нь БҮТЭН зогсоно — худал явц
               * үзүүлэхээр огт үзүүлэхгүй нь дээр.
               */}
              {i === index && (
                <span
                  key={index}
                  aria-hidden
                  className={`block size-full rounded-full bg-white ${
                    autoplay ? 'hero-dot-fill' : ''
                  }`}
                  style={autoplay ? { animationDuration: `${INTERVAL_MS}ms` } : undefined}
                />
              )}
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
