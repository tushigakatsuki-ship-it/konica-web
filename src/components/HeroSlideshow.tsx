import { useEffect, useState } from 'react';
import { HERO_IMAGES } from '../data/site';

/**
 * Нүүр хуудасны дэвсгэр зургууд — автоматаар солигдоно.
 *
 * Зураг угаалгах гэж буй хүнд «энэ газар ямар чанартай ажилладаг вэ» гэдгийг
 * градиент биш, бодит ажлын зураг л хэлж чадна.
 *
 * Гүйцэтгэлийн шийдлүүд:
 *   • ЗӨВХӨН эхний зураг `fetchPriority="high"`-тэй.
 *   • ⚠️ Бусад зургийг эхний зураг ГАРЧ ИРТЭЛ огт үүсгэхгүй. `loading="lazy"`
 *     нь энд ТУСЛАХГҮЙ: дөрвүүлээ дэлгэцийн харагдах хэсэгт (`absolute
 *     inset-0`) байрладаг тул хөтөч бүгдийг нь ШУУД татна. Үр дүнд нь нүүр
 *     хуудас нээхэд дөрвөн зураг зэрэг татагдаж, эхнийх нь удаашрана.
 *   • Солих нь `opacity` шилжилт: layout дахин тооцоологддоггүй тул хямд.
 *   • Таб нуугдсан үед зогсоно — арын табанд таймер эргүүлэх нь батарей иддэг.
 *
 * Хүртээмж:
 *   • `prefers-reduced-motion` тохируулсан хүнд автомат солилт ажиллахгүй —
 *     хөдөлгөөнөөс толгой эргэдэг хүмүүс байдаг.
 *   • Зургууд бүгд `aria-hidden` — чимэглэл учир дэлгэц уншигчид хэрэггүй.
 */

/**
 * Хэдэн секунд тутам солих вэ.
 *
 * 2 секунд нь хэт хурдан байв — зураг тогтож амжаагүй байхад дараагийнх нь
 * ирж, дэвсгэр анивчсан мэдрэмж төрүүлдэг. 5 секунд нь зураг бүрийг үнэхээр
 * ХАРАХ зав өгнө.
 *
 * ⚠️ Шилжилтийн хугацаа (700ms) нь мөчлөгийн 14% — зураг тогтох зай элбэг.
 */
const INTERVAL_MS = 5000;

const prefersReducedMotion = (): boolean =>
  typeof matchMedia === 'function' &&
  matchMedia('(prefers-reduced-motion: reduce)').matches;

export default function HeroSlideshow() {
  const [index, setIndex] = useState(0);

  /**
   * Эхний зураг гарсны дараа л үлдсэнийг DOM-д нэмнэ.
   *
   * Ингэснээр анхны зурагдалт нь ЗӨВХӨН нэг зургийн татахыг хүлээнэ.
   * Үлдсэн нь араас чимээгүй ирнэ — эхний солилт 5 секундын дараа тул
   * амжина.
   */
  const [ready, setReady] = useState(false);

  /**
   * Эхний зургийн ойртолтыг асаах түлхүүр.
   *
   * ⚠️ Үүнгүй бол ЭХНИЙ зураг хөдөлдөггүй. CSS-ийн шилжилт нь утга
   * ӨӨРЧЛӨГДӨХӨД л ажилладаг: эхний зурагдалтад `index === 0` тул React
   * түүнийг шууд эцсийн хэмжээтэй нь буулгаж, шилжих зай үлдэхгүй.
   *
   * Нэг кадр хүлээгээд асаахад утга өөрчлөгдөж, ойртолт эхэлнэ. Хуудас
   * нээх агшин бол хамгийн их харагддаг тул энэ нь чухал.
   */
  const [started, setStarted] = useState(false);
  useEffect(() => {
    const id = requestAnimationFrame(() => setStarted(true));
    return () => cancelAnimationFrame(id);
  }, []);

  useEffect(() => {
    if (HERO_IMAGES.length < 2 || prefersReducedMotion()) return;

    const timer = setInterval(() => {
      if (document.hidden) return;
      setIndex((current) => (current + 1) % HERO_IMAGES.length);
    }, INTERVAL_MS);

    return () => clearInterval(timer);
  }, []);

  /*
   * Зураг байхгүй бол градиент руу буцна.
   *
   * `public/hero/` хоосон байхад хуудас эвдрэх ёсгүй — шинэ deploy дээр зураг
   * оруулж амжаагүй байх нь бодитой.
   */
  if (HERO_IMAGES.length === 0) {
    return (
      <div
        aria-hidden
        className="absolute inset-0 bg-gradient-to-br from-brand-400 via-brand-500 to-brand-700"
      />
    );
  }

  return (
    /*
      * ⚠️ `isolate` ЗААВАЛ — доорх цэнхэр хальс `mix-blend-color`
      * хэрэглэдэг. Үүнгүй бол холилт нь энэ хэсгээс ГАДАГШ, доор нь
      * байрлах юмтай холбогдож болно.
      *
      * `bg-ink` нь зураг ачаалагдтал харагдах өнгө. Урьд нь `bg-brand-500`
      * байсан ч одоо дэвсгэрийг будахаа больсон тул цэнхэр анивчилт нь
      * эцсийн харагдацтай таарахгүй байв.
      */
    <div aria-hidden className="absolute inset-0 isolate overflow-hidden bg-ink">
      {HERO_IMAGES.map((image, i) =>
        i > 0 && !ready ? null : (
          <img
            key={image.src}
            src={image.src}
            alt=""
            onLoad={i === 0 ? () => setReady(true) : undefined}
            /*
             * ⚠️ Алдаа гарсан ч үлдсэнийг нээнэ. Эс тэгвээс эхний зураг
             * ирэхгүй бол дэвсгэр мөнхөд ганц өнгө хэвээр үлдэнэ.
             */
            onError={i === 0 ? () => setReady(true) : undefined}
            fetchPriority={i === 0 ? 'high' : 'low'}
            decoding="async"
            /*
             * ⚠️ Хүрээ нарийн байх бүх өргөнд байрлалыг БАРУУН тийш шилжүүлнэ.
             *
             * Эх зураг 1376×768 (харьцаа 1.79) бөгөөд хэвлэгч нь голоос
             * баруун тийш байрладаг. `object-cover` нь хүрээний харьцаа 1.79-өөс
             * бага үед ӨРГӨНӨӨС, голоос нь тэгш тасалдаг — субьект нь голд
             * биш тул баруун тал нь эхэлж алга болно.
             *
             * ⚠️ Урьд нь `sm:` (640px) дээр голд нь буцаадаг байсан бөгөөд
             * тайлбар нь «sm-ээс дээш бүх зураг багтана» гэсэн. Тэр нь БУРУУ
             * байв — хүрээний өндөр нь текстээс хамаардаг тул бодит хэмжилт:
             *
             *   375px  → харьцаа 0.68 → өргөний  38% харагдана
             *   768px  → харьцаа 1.19 → өргөний  67%   (iPad — хэвлэгч тасарна)
             *   1024px → харьцаа 1.53 → өргөний  85%
             *   1280px → харьцаа 1.91 → өргөний 100%   ← энд л жинхэнэ багтана
             *
             * Тиймээс голд нь буцаах цэг `xl:` (1280px). Дунд өргөнд шилжилтийг
             * сулруулна: тасрах хэмжээ багасах тусам 50% руу ойртуулахгүй бол
             * зургийн баруун ирмэг хоосон зурвас болж гарч ирнэ.
             */
            /*
             * ⚠️ Хөнгөн тодруулга — өнгийг ГУЙВУУЛАХГҮЙ.
             *
             * Эх зургууд нь үйлдвэрлэгчийн каталогийн кадр: оффисын
             * сарниулсан гэрэлд авсан тул өөрсдөө бага зэрэг бүдэг,
             * контраст багатай. Дээр нь доорх халхавч нэмэгдэж, нийтдээ
             * «бараан» мэдрэмж төрүүлдэг байв.
             *
             * `brightness`/`saturate` нь өнгөний ӨНЦГИЙГ (hue) хөнддөггүй —
             * зөвхөн тодрол нэмнэ. Утгууд нь болгоомжтой: 1.2-оос дээш
             * бол цагаан хана шатаж, машины цагаан бүрхүүлтэй нийлнэ.
             */
            className="absolute inset-0 size-full object-cover object-[72%_center] brightness-110 saturate-[1.18] contrast-[1.05] will-change-[opacity,transform] sm:object-[66%_center] lg:object-[60%_center] xl:object-center"
            /*
             * ── Ken Burns: удаан ойртолт ──────────────────────────────
             *
             * Урьд нь ердөө 700ms бүдгэрэлт байв: зураг солигдоод ЗОГСДОГ
             * тул дэвсгэр нь хөдөлгөөнгүй зураг мэт мэдрэгддэг байлаа.
             *
             * Одоо идэвхтэй зураг 7 секундын турш 1 → 1.06 хүртэл ААЖИМ
             * ойртоно. Солигдох мөчлөг 5 секунд тул ойртолт дуусахаас өмнө
             * дараагийнх нь эхэлдэг — хөдөлгөөн ТАСРАЛТГҮЙ мэдрэгдэнэ.
             *
             * ⚠️ Чиглэл нь ээлжилнэ (тэгш дугаар ойртоно, сондгой нь
             * холдоно). Бүгд нэг тийш хөдөлвөл дөрөв дэх зураг дээр хүн
             * давталтыг нь анзаарч, хямд мэдрэмж төрүүлнэ.
             *
             * ⚠️ Идэвхгүй зураг дээр `transform`-ийн үргэлжлэл 0 — дараа
             * нь эргэж ирэхэд ойртолт ЭХНЭЭСЭЭ эхлэх ёстой. Үүнгүй бол
             * хоёр дахь удаагаасаа хөдөлгөөнгүй болно.
             *
             * `prefers-reduced-motion` үед `index.css`-ийн нэгдсэн дүрэм
             * бүх үргэлжлэлийг 0.01ms болгодог тул зураг шууд эцсийн
             * байрлалдаа суух бөгөөд энэ нь зүгээр л бага зэрэг ойрсон
             * хөдөлгөөнгүй зураг — эвдрэхгүй.
             */
            style={{
              opacity: i === index ? 1 : 0,
              /*
               * ⚠️ Зөвхөн ойртолт биш, ШИЛЖИЛТ ч бий.
               *
               * Цэвэр `scale` нь механик мэдрэмж өгдөг — зураг байрандаа
               * томорч байгаа нь камерын хөдөлгөөн биш, объектив сунаж
               * байгаа мэт. Бодит камер ойртохдоо бага зэрэг хажуу тийш
               * ч шилждэг тул `translate` нэмэв.
               *
               * ⚠️ ШИЛЖИЛТ нь ЗӨВХӨН ойртсон үед. `scale(1)` дээр
               * илүүдэл зай БАЙХГҮЙ тул тэнд шилжүүлбэл зургийн ирмэг
               * гарч, хоосон зурвас харагдана. Тиймээс сондгой зургийн
               * ТӨГСГӨЛ (scale 1) нь үргэлж `translate(0,0)`.
               *
               * Тэгш: ойртоно  (1 → 1.06), зүүн дээш шилжинэ
               * Сондгой: холдоно (1.06 → 1), баруун доошоос төв рүү
               */
              transform:
                i === index && started
                  ? i % 2 === 0
                    ? 'scale(1.06) translate(-1.1%, -0.7%)'
                    : 'scale(1) translate(0, 0)'
                  : i % 2 === 0
                    ? 'scale(1) translate(0, 0)'
                    : 'scale(1.06) translate(1.1%, 0.6%)',
              transitionProperty: 'opacity, transform',
              transitionTimingFunction: 'cubic-bezier(0.4, 0, 0.2, 1), linear',
              transitionDuration: i === index ? '1100ms, 7000ms' : '1100ms, 0ms',
            }}
          />
        ),
      )}

      {/*
       * ── 1. ЦЭНХЭР ХАЛЬС — брэндийн уур амьсгал ─────────────────────
       *
       * `mix-blend-color` нь ӨНГИЙГ (hue + saturation) энэ давхаргаас,
       * ГЭРЭЛТҮҮЛГИЙГ доорх зурагнаас авна. `bg-brand-500` нь логоны
       * хавтантай ижил токен тул өнгө нь тодорхойлолтоороо таарна.
       *
       * ⚠️ Хальс нь ЖИГД БИШ, радиал градиент — тайлбарыг `index.css`-ийн
       * `hero-tint`-ээс үз. Товчоор: МАШИН дээр нүхтэй тул тэр нь жинхэнэ
       * өнгөөрөө харагдаж, эргэн тойрон нь цэнхэрт уусна.
       *
       * Жигд хальс нь хоёр шаардлагын аль нэгийг үргэлж золиосолдог:
       * 50% дээр зураг будагдаж, 25% дээр цэнхэр алга болно.
       *
       * Доорх халхавч нь СААРМАГ (`ink`) — цэнхэр байвал хальс дээр
       * хальс давхарлаж, будагдах асуудал буцаж ирнэ.
       */}
      <div className="hero-tint absolute inset-0" />

      {/*
       * ── 2. ЦЭНХЭРИЙН ГҮН — зөвхөн дэвсгэр дээр ─────────────────────
       *
       * `mix-blend-color` нь ГЭРЭЛТҮҮЛГИЙГ зурагнаас авдаг тул цайвар
       * оффисын зураг дээр хальс дангаараа цайсан, бүдэг цэнхэр болдог.
       * Энэ давхарга `multiply`-аар гэрэлтүүлгийг нь бууруулж, брэндийн
       * цэнхэрийг жинхэнэ хүч рүү нь буцаана.
       *
       * ⚠️ Нүх нь `hero-tint`-тэй ижил (`--hero-subject`) тул машин
       * бүрэн тод хэвээр — гүн нь ЗӨВХӨН эргэн тойронд нэмэгдэнэ.
       */}
      <div className="hero-depth absolute inset-0" />

      {/*
       * ── 3. Текстийн контраст — өнгө ЗАСАХГҮЙ ───────────────────────
       *
       * ⚠️ Урьд нь энд `bg-brand-500 mix-blend-color` тонгоруулга байсан:
       * зургийн өнгийг бүхэлд нь брэндийн цэнхэр рүү татдаг байв. Үр дүнд
       * нь хэвлэгчийн бодит өнгө (саарал метал, модон ширээ, дэлгэцийн
       * гэрэл) бүгд нэг цэнхэр болж, зураг нь ГЭРЭЛ ЗУРАГ биш, будсан
       * чимэглэл мэт харагддаг байлаа.
       *
       * Одоо зураг ЖИНХЭНЭ ӨНГӨӨРӨӨ гарна — `ppm32.mn` дээрх ажлын
       * зургуудтай ижил. Брэндийн өнгө нь товч, гарчиг, толгой дээр
       * хангалттай байгаа тул дэвсгэрийг будах шаардлагагүй.
       *
       * Үлдсэн хоёр давхарга нь ЗӨВХӨН уншигдац: цагаан гарчиг, товч
       * зургийн цайвар хэсэг дээр суувал алга болно. Тиймээс саармаг
       * бараан (`--color-ink`) — цэнхэр БИШ, эс бөгөөс өнгө дахин
       * хальсална.
       *
       * ⚠️ Утгууд нь урьд нь илүү гүн байв (85/70/45). Зургууд тодорч,
       * цэнхэр нь өөрөө гүнтэй болсон тул тийм халхавч нийлээд «бараан»
       * мэдрэмж төрүүлдэг байлаа. Одоо гарчгийг уншуулахад хүрэлцэх
       * хамгийн бага утгууд.
       *
       * Хэвтээ: бичиг суусан ЗҮҮН тал гүн, баруун тал ЦЭВЭР — машин
       * тэндээс жинхэнэ өнгөөрөө харагдана.
       * Босоо: доод ирмэг бага зэрэг — слайдын цэгүүд тэнд сууна.
       */}
      {/*
       * ⚠️ Утас ба ширээний компьютерт ӨӨР халхавч.
       *
       * Ширээн дээр бичиг нь зүүн талд багтдаг тул халхавч зүүнээс баруун
       * тийш бүдгэрч, хэвлэгч баруун талд ЦЭВЭР харагдана.
       *
       * Утсан дээр бичиг БҮТЭН өргөнөөр тардаг: тэр градиентийг хэвээр
       * үлдээвэл гарчгийн баруун үзүүр («…үйлчилгээ») зургийн гэгээн
       * хэсэг дээр сууж, амбер текст уншигдахаа болино. Тиймээс нарийн
       * дэлгэцэд халхавчийг жигд гүн болгоно.
       */}
      <div className="absolute inset-0 bg-gradient-to-r from-ink/72 via-ink/45 to-ink/25 sm:from-ink/62 sm:via-ink/24 sm:to-transparent" />
      <div className="absolute inset-0 bg-gradient-to-t from-ink/28 via-transparent to-transparent" />

      {HERO_IMAGES.length > 1 && (
        <div className="absolute bottom-4 left-1/2 flex -translate-x-1/2 gap-2 sm:bottom-6">
          {HERO_IMAGES.map((image, i) => (
            <button
              key={image.src}
              type="button"
              onClick={() => setIndex(i)}
              aria-label={`${i + 1} дэх зураг`}
              aria-current={i === index}
              className={`h-1.5 rounded-full transition-all ${
                i === index ? 'w-6 bg-white' : 'w-1.5 bg-white/50 hover:bg-white/80'
              }`}
            />
          ))}
        </div>
      )}
    </div>
  );
}
