import { HERO_IMAGES } from '../data/site';

/**
 * Машинуудын зураг — тасралтгүй хажуу тийш гүйдэг эгнээ.
 *
 * ── Яагаад hero-гийн зургуудыг ДАХИН хэрэглэж байна вэ ───────────
 *
 * Хийсэн ажлын зураг сан дотор байхгүй. Хүсэлт нь «байгаа бизхаб, R2
 * машины зургийг хажуу тийш гүйлгэ» байсан тул `HERO_IMAGES`-ийг л
 * ашиглав.
 *
 * ⚠️ Тэдгээр нь hero-гийн ДЭВСГЭР ч мөн — өөрөөр хэлбэл нэг зураг хоёр
 * газар гарна. Хийсэн ажлын жинхэнэ зураг ирэхэд энэ эгнээг тэдгээрээр
 * солих нь зөв: `HERO_IMAGES`-ийн оронд шинэ жагсаалт өгөхөд л хангалттай.
 *
 * ── Яагаад товшигддоггүй вэ ──────────────────────────────────────
 *
 * Эгнээ нь чимэглэл — хаашаа ч хөтөлдөггүй. Хөдөлж буй зүйлийг товшуур
 * болговол хүн хөдөлж буй байг барих гэж хөөцөлдөнө. Хэрэв хожим
 * ангилал руу хөтлөх бол гүйлтийг нь зогсоох хэрэгтэй болно.
 */

/** Нэг бүтэн эргэлт хэдэн секунд болох вэ. */
const STRIP_SECONDS = 40;

export default function MachineStrip() {
  /*
   * Зураг байхгүй бол хэсгийг огт үзүүлэхгүй — хоосон саарал зурвас
   * хуудсыг эвдэрсэн мэт харуулна.
   */
  if (HERO_IMAGES.length === 0) return null;

  /*
   * ⚠️ Жагсаалт ХОЁР ДАХИН. Гүйлт нь замын тал хүртэл явж эхэндээ буцдаг
   * тул хоёр дахь хуулбар нь тэр агшинд яг анхныхаа байрлалд ирсэн байх
   * ёстой — үгүй бол эргэлт бүрт үсрэлт мэдэгдэнэ.
   */
  const loop = [...HERO_IMAGES, ...HERO_IMAGES];

  return (
    <section className="machine-strip-stage overflow-hidden py-10 sm:py-14">
      {/*
        * ⚠️ Завсрыг `gap`-аар өгч БОЛОХГҮЙ.
        *
        * Гүйлт нь замын яг ТАЛ (-50%) хүртэл явдаг тул тал нь нэг бүтэн
        * хуулбар байх ёстой. `gap` нь N элементийн хооронд N−1 завсар
        * тавьдаг: хоёр хуулбар дээр 8 карт, 7 завсар болж, тал нь
        * 4 карт + 3.5 завсар болно — хагас завсраар зөрөх тул эргэлт
        * бүрт 12px үсрэлт мэдэгдэнэ.
        *
        * Завсрыг карт бүрийн ӨӨРИЙНХ нь баруун захад өгвөл зам нь яг
        * 2 × (карт + завсар) болж, тал нь бүтэн хуулбар дээр таарна.
        */}
      <div
        className="machine-strip flex"
        style={{ ['--strip-seconds' as string]: `${STRIP_SECONDS}s` }}
      >
        {loop.map((image, i) => (
          <figure
            /*
             * ⚠️ `key` нь зам БИШ — жагсаалт давхарласан тул зам давхардана.
             * Байрлалыг нь түлхүүр болгоно.
             */
            key={i}
            className="relative mr-4 aspect-[4/3] w-64 shrink-0 overflow-hidden rounded-xl border border-hairline bg-card sm:mr-6 sm:w-80"
          >
            <img
              src={image.src}
              alt=""
              /*
               * Эгнээ бол чимэглэл тул дэлгэц уншигчид хэрэггүй. Мөн бүх
               * зураг hero дээр аль хэдийн татагдсан байдаг ч `lazy` нь
               * хоёр дахь хуулбарыг нь хойшлуулна.
               */
              aria-hidden
              loading="lazy"
              decoding="async"
              className="size-full object-cover"
            />
          </figure>
        ))}
      </div>
    </section>
  );
}
