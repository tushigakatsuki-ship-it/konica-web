/**
 * Хоёр текстийг ээлжлэн ТҮЛХЭЖ солих.
 *
 * Мөчлөг:
 *   1. 1-р текст ЗҮҮНЭЭС баруун тийш түлхэгдэн орж ирнэ
 *   2. Хэсэг зогсоно
 *   3. 1-р текст зүүн тийш шахагдаж гарахад 2-р текст БАРУУНААС орж ирнэ
 *   4. 2-р текст зогсоно
 *   5. 2-р текст баруун тийш буцаж гарахад 1-р текст дахин зүүнээс орно
 *
 * ── Яагаад бүхэлдээ CSS вэ (JS таймер БИШ) ───────────────────────
 *
 * `setInterval`-аар слайд солих нь хоёр газраа унадаг:
 *
 *   1. `index.css` доторх нэгдсэн `prefers-reduced-motion` дүрэм нь ЗӨВХӨН
 *      `animation`, `transition`-ыг хумьдаг тул JS таймер түүнд баригдахгүй.
 *   2. Таб нуугдсан үед хөтөч таймерыг 1 секунд болгож удаашруулдаг тул
 *      хэрэглэгч буцаж ирэхэд слайд дунд замдаа гацсан байдаг.
 *
 * CSS `animation` нь хоёуланг нь өөрөө зохицуулна.
 *
 * ── Байрлал ──────────────────────────────────────────────────────
 *
 * Хоёр слайд НЭГ grid нүдэнд давхарлана (`grid-area: 1/1`). Ингэснээр
 * хайрцгийн өндөр нь ХАМГИЙН ӨНДӨР слайдаар тогтоно — `absolute` ашиглавал
 * өндөр 0 болж, доорх агуулга дээшээ мөлхөх байлаа. Мөр солигдоход хайрцаг
 * үсрэхгүй.
 */

interface Props {
  /** Слайд бүр нэг буюу хэд хэдэн мөр. */
  slides: readonly (readonly string[])[];
  className?: string;
}

export default function PushSlides({ slides, className }: Props) {
  return (
    <span className={`grid overflow-hidden ${className ?? ''}`}>
      {slides.map((lines, i) => (
        <span
          key={lines.join('|')}
          /*
            Хоёулаа НЭГ нүдэнд — өндөр нь өндөр слайдаараа тогтоно.
            `push-slide-1` / `push-slide-2` нь мөчлөгийн өөр өөр үе шатыг
            хариуцна (`index.css`).
          */
          style={{ gridArea: '1 / 1' }}
          className={i === 0 ? 'push-slide-1 block' : 'push-slide-2 block'}
        >
          {lines.map((line) => (
            <span key={line} className="block">
              {line}
            </span>
          ))}
        </span>
      ))}
    </span>
  );
}
