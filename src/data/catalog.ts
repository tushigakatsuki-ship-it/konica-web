/** Категори тус бүрийн эхний (хамгийн хямд) үнэ — "…-с" гэж харуулахад. */
export const categoryFrom = (category: ServiceCategory): number =>
  Math.min(
    ...SERVICES.filter((s) => s.category === category).map((s) =>
      Number(s.price.replace(/[^0-9]/g, '')) || 0,
    ),
  );

export const byCategory = (category: ServiceCategory): readonly ServiceItem[] =>
  SERVICES.filter((s) => s.category === category);
