/**
 * НЭГ талбарт бичсэн холбоо барих утгыг задлана.
 *
 * ── Яагаад нэг талбар вэ ─────────────────────────────────────────
 *
 * Хоёр талбар («Утас», «И-мэйл») зэрэгцэн байхад аль нэгийг нь л бөглөх
 * ёстой гэдэг нь маягтаас харагддаггүй: хэрэглэгч хоёуланг нь бөглөх гэж
 * оролдоод, и-мэйлгүй бол «дутуу бөглөлөө» гэж эргэлзэнэ.
 *
 * ── Яагаад сервер тал ХУВААГДСАН хэвээр вэ ───────────────────────
 *
 * `WorkLog.phone` нь Konica апп дээрх ТУСДАА талбар бөгөөд ажилтан түүгээр
 * шүүж, дарж залгадаг. И-мэйлийг тэнд хийвэл залгах товч ажиллахгүй. Тиймээс
 * интерфейс нь нэгдсэн ч, сервер рүү явахдаа `phone` / `email` болж сална.
 */

export interface Contact {
  phone: string;
  email: string;
}

/** `@` агуулсан бүхнийг и-мэйл гэж үзнэ — хэлбэрийн шалгалт тусдаа. */
const looksLikeEmail = (value: string): boolean => value.includes('@');

/**
 * Хэрэглэгчийн бичсэн мөрийг `phone` / `email` болгож хуваана.
 *
 * ⚠️ Утаснаас цифр биш бүхнийг зайлуулна: хэрэглэгч `9900-1234`,
 * `+976 99001234`, `(99) 001234` гэх мэтээр бичих нь энгийн зүйл бөгөөд
 * эдгээрийг татгалзвал зөв дугаартай хүн маягтаа дуусгаж чадахгүй.
 *
 * ⚠️ `+976` улсын код нь ХАСАГДАНА. `+97699001234` → `97699001234` болбол
 * 8 оронтой шалгалтад унана. Тиймээс эхний `976`-г тусад нь салгана —
 * гэхдээ ЗӨВХӨН нийт урт нь 11 болсон үед: `97612345` гэдэг нь өөрөө
 * хүчинтэй 8 оронтой дугаар (Мобиком) тул түүнийг таслах нь алдаа.
 */
export const splitContact = (raw: string): Contact => {
  const value = raw.trim();
  if (!value) return { phone: '', email: '' };

  if (looksLikeEmail(value)) return { phone: '', email: value };

  let digits = value.replace(/\D/g, '');
  if (digits.length === 11 && digits.startsWith('976')) digits = digits.slice(3);

  return { phone: digits, email: '' };
};

/**
 * Задалсан утгыг буцааж НЭГ мөр болгоно.
 *
 * Хуудсыг дахин ачаалах, өмнөх захиалгаас утгыг сэргээх зэрэгт хэрэгтэй:
 * хадгалалт нь хуваагдсан хэвээр учир талбарт юу харуулахыг эндээс мэднэ.
 */
export const joinContact = (contact: Contact): string =>
  contact.email.trim() || contact.phone.trim();
