/**
 * Нэг захиалгын хязгаарууд — КЛИЕНТ, СЕРВЕР ХОЁРЫН ганц эх сурвалж.
 *
 * ⚠️ Яагаад `src/lib` дотор байгаа вэ (`api/` доор биш):
 *
 * Хязгаарыг хоёр газар тусад нь бичвэл нэгийг нь өөрчлөөд нөгөөг мартах нь
 * цаг хугацааны асуудал. Тэр үед хэрэглэгч 40 зураг сонгож, бүгдийг нь
 * бэлдэж (хэдэн арван секунд), дараа нь сервер «хэтэрсэн» гэж татгалзана —
 * хийсэн ажил бүхэлдээ хаягдана.
 *
 * `api/_shared.ts` нь аль хэдийн `../src/lib/order`-оос импортолдог тул
 * ийм чиглэлийн хамаарал шинэ зүйл биш.
 */

/**
 * Зураг бүрээс хэдэн файл гарах вэ.
 *
 *   `print`    — хэвлэхэд бэлэн, 300dpi JPEG
 *   `original` — хэрэглэгчийн эх файл (ажилтан гараар засахад хэрэгтэй)
 */
export const FILES_PER_PHOTO = 2;

/**
 * Нэг захиалгад орох зургийн дээд тоо.
 *
 * ⚠️ Энэ бол ТЕХНИКИЙН хязгаар, зөвлөмж БИШ. 100 зураг нь ойролцоогоор
 * 600–700MB бөгөөд гар утасны сүлжээгээр 40–60 минут илгээгдэнэ. Тиймээс
 * интерфейс дээр хугацааны анхааруулга ЗААВАЛ байх ёстой — тоо нь
 * зөвшөөрөгдөж байгаа нь тэр нь ухаалаг гэсэн үг биш.
 */
export const MAX_PHOTOS_PER_ORDER = 100;

/** Серверийн файлын хязгаар — зургийн хязгаараас ГАРГАЖ авна, тусад нь биш. */
export const MAX_FILES = MAX_PHOTOS_PER_ORDER * FILES_PER_PHOTO;

/**
 * Нэг файлын дээд хэмжээ.
 *
 * Утсаар авсан зураг ихэвчлэн 3–8MB. 30MB нь мэргэжлийн камерын RAW-аас
 * хөрвүүлсэн том JPEG-ийг ч багтаана.
 */
export const MAX_FILE_BYTES = 30 * 1024 * 1024;

/**
 * Нэг зургийн ойролцоо хэмжээ, MB — хугацааны тооцоонд.
 *
 * `print` ~1.5MB + `original` ~5MB. Утасны камерын хэмжээ өсөж байгаа тул
 * энэ нь ДООД тал нь бөгөөд тооцоо нь өөдрөг тал руугаа хазайна.
 */
export const APPROX_MB_PER_PHOTO = 6.5;

/**
 * Хэдэн зурагнаас эхлээд хугацааны анхааруулга харуулах вэ.
 *
 * 15 зураг ≈ 100MB ≈ дунджийн 4G дээр 7 минут. Түүнээс доош бол ихэнх
 * хэрэглэгч хүлээхэд бэрхшээлгүй.
 */
export const SLOW_UPLOAD_THRESHOLD = 15;

/*
 * ── Илгээх хурдны таамаглал (МЕГАБАЙТ / минут) ──────────────────────
 *
 * ⚠️ Мегабайт, мегабит БИШ. Сүлжээний сурталчилгаа Mbps-ээр яридаг тул
 * 8-д хуваахаа мартвал бүх тооцоо 8 дахин өөдрөг гарна.
 *
 * ⚠️ Улаанбаатарын гар утасны сүлжээнд ИЛГЭЭХ хурд ТАТАХААС хамаагүй бага.
 * «Хурдан интернэттэй» хэрэглэгч ч илгээхдээ удаан байж болно.
 */
/** Сайн WiFi — 8 Mbps upload. */
export const FAST_MB_PER_MIN = 60;
/** Дундаж 4G — 2 Mbps upload. */
export const SLOW_MB_PER_MIN = 15;

/**
 * Хамгийн муу тохиолдолд илгээх хугацаа, МИНУТААР.
 *
 * `PUT_EXPIRES_SEC` энэ тооноос ХАМААРНА — хоёрыг тусад нь тааварлаж
 * болохгүй (доорх тайлбарыг үз).
 */
export const worstCaseUploadMinutes = (photos = MAX_PHOTOS_PER_ORDER): number =>
  Math.ceil((photos * APPROX_MB_PER_PHOTO) / SLOW_MB_PER_MIN);

/**
 * Presigned PUT хаягийн хүчинтэй хугацаа.
 *
 * ⚠️ ЭНЭ БОЛ ЗАХИАЛГА УНАГААХ ЧАДВАРТАЙ ТООЦОО, зүгээр нэг тохиргоо биш.
 *
 * Урьд нь 20 минут байсан. Гэтэл 100 зураг (≈650MB) нь дундаж 4G дээр
 * 43 минут, сул сүлжээнд 87 минут илгээгддэг. Өөрөөр хэлбэл хэрэглэгч
 * 20 минут зургаа илгээж байгаад, 46 дахь зураг дээр гарын үсэг нь
 * хүчингүй болж `403` авна.
 *
 * Хамгийн муу нь: `403` бол 4xx учир байршуулагч түүнийг БАЙНГЫН алдаа
 * гэж үзэж дахин ОРОЛДДОГГҮЙ (`upload.ts` доторх `permanent`) — тэр нь
 * зөв шийдвэр, учир нь хугацаа дууссан гарын үсгийг давтаад ижил хариу
 * ирнэ. Үр дүнд нь 40 минут илгээсэн захиалга бүхэлдээ унана.
 *
 * Одоо хамгийн муу тохиолдлын хугацааг ХОЁР ДАХИН нөөцтэй нөхнө: дахин
 * оролдлого, сүлжээний тасалдал, хоёр дахь давталт бүгд энэ зайд багтана.
 * Аюулгүй байдлын өртөг бага: хаяг тус бүр ГАНЦ түлхүүрт, ЗӨВХӨН бичих
 * эрхтэй бөгөөд таамаглах боломжгүй `uploadId` дотор байрлана.
 */
export const PUT_EXPIRES_SEC = worstCaseUploadMinutes() * 2 * 60;
