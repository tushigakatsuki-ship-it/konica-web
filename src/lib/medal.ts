export interface ArcGlyph {
  char: string;
  /** Тойрог дээрх байрлал, радиан. Дээд цэг нь `-π/2`. */
  angle: number;
  /** Тэмдэгтийг эргүүлэх өнцөг — суурь шугам нь тойрогт шүргэлцэнэ. */
  rotation: number;
}

/**
 * Бичвэр нумын аль талд байрлах вэ.
 *
 * Доод нумын тэмдэгтүүд нь 180° ЭРГЭНЭ: эс бөгөөс толгойгоороо доошоо
 * харна. Бодит медалийн доод хэсгийн бичээс (сум, он) ингэж сийлэгддэг.
 */
export type ArcSide = 'top' | 'bottom';

export interface ArcTextLayout {
  glyphs: ArcGlyph[];
  /** Бичвэрийн эзэлсэн нум, радиан. */
  span: number;
  /** Зөвшөөрөгдөх нумаас хэтэрсэн эсэх. */
  overflow: boolean;
}

/**
 * Бичвэрийг медалийн ДЭЭД нумаар байрлуулна.
 *
 * ── Яагаад өргөнийг ГАДНААС авдаг вэ ─────────────────────────────
 *
 * Тэмдэгт бүрийг ижил өнцгөөр тараах нь буруу: «ЛШ» ба «ІІ» ижил зай
 * эзлэхгүй тул үсэг хоорондын зай эвгүй үсэрнэ. Зөв арга нь тэмдэгтийн
 * БОДИТ өргөнөөр тооцох — тэр нь `ctx.measureText` шаарддаг.
 *
 * Хэмжилтийг дуудагч тал хийж, энд зөвхөн тоо дамжуулснаар цөм нь
 * canvas-гүй, тестлэгдэх боломжтой хэвээр үлдэнэ.
 *
 * ── Нумын урт ба өнцөг ───────────────────────────────────────────
 *
 * Тойрог дээрх нумын урт нь `радиус × өнцөг`. Тиймээс өнцөг нь
 * `урт ÷ радиус`. Пикселийн өргөнийг шууд өнцөг болгож ашиглах нь
 * радиусыг үл тоомсорлож, жижиг медальд үсэг давхцаж, томд нь тарна.
 */
export function layoutArcText(
  text: string,
  widths: readonly number[],
  radius: number,
  maxArc = (200 * Math.PI) / 180,
  side: ArcSide = 'top',
): ArcTextLayout {
  const chars = [...text];

  // Хоосон бичвэр, эсвэл утгагүй радиус — юу ч зурахгүй, NaN гаргахгүй.
  if (chars.length === 0 || radius <= 0) {
    return { glyphs: [], span: 0, overflow: false };
  }

  const total = widths.reduce((sum, w) => sum + (Number.isFinite(w) ? w : 0), 0);
  const span = total / radius;

  /*
   * Canvas дээр 0 радиан нь баруун тийш, эерэг өнцөг цагийн зүүний дагуу
   * (y доошоо). Тиймээс дээд цэг нь `-π/2`, доод цэг нь `π/2`.
   */
  const centre = side === 'top' ? -Math.PI / 2 : Math.PI / 2;

  /*
   * ⚠️ Доод нумд тэмдэгтүүд БАРУУНААС ЗҮҮН тийш байрлана.
   *
   * Доод хагаст өнцөг өсөхөд цэг нь зүүн тийш явдаг. Дээдтэй ижил
   * чиглэлээр байрлуулбал бичвэр урвуу дараалалтай уншигдана — «СУМ» нь
   * «МУС» болно.
   */
  const dir = side === 'top' ? 1 : -1;
  const start = centre - (dir * span) / 2;

  let walked = 0;
  const glyphs = chars.map((char, index) => {
    const width = Number.isFinite(widths[index]) ? widths[index] : 0;
    // Тэмдэгтийн ТӨВ рүү явна — эхлэл рүү биш, эс бөгөөс хагасаар хазайна.
    const angle = start + (dir * (walked + width / 2)) / radius;
    walked += width;

    /*
     * Тэмдэгт нь гадагшаа "босоо" харагдах ёстой. Суурь шугам нь тойрогт
     * шүргэлцэх тул эргэлт нь өнцөг дээр `π/2` нэмсэн утга. Доод нумд
     * үүн дээр 180° нэмнэ — эс бөгөөс толгойгоороо доошоо харна.
     */
    const rotation = angle + Math.PI / 2 + (side === 'bottom' ? Math.PI : 0);
    return { char, angle, rotation };
  });

  return { glyphs, span, overflow: span > maxArc };
}

/**
 * Бичвэр багтахгүй бол фонтын хэмжээг хэр багасгах вэ.
 *
 * Хэрэглэгчийг «хэт урт» гэж зогсоохын оронд автоматаар багасгах нь
 * зөв: медальд бичих үг нь ихэвчлэн нэр, огноо — хасах зүйл байдаггүй.
 * Гэхдээ хязгааргүй багасгавал уншигдахаа болино.
 */
export const fitFontSize = (
  span: number,
  maxArc: number,
  fontSize: number,
  minFontSize: number,
): number => {
  if (span <= maxArc || span <= 0) return fontSize;
  return Math.max(minFontSize, Math.floor((fontSize * maxArc) / span));
};

